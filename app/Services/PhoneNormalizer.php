<?php

namespace App\Services;

class PhoneNormalizer
{
    /**
     * توحيد أرقام الجوال اليمنية والسعودية.
     */
    public function normalize(
        ?string $phone
    ): ?string {
        if ($phone === null) {
            return null;
        }

        $phone = trim($phone);

        if ($phone === '') {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | Arabic / Persian Digits
        |--------------------------------------------------------------------------
        */

        $phone = strtr(
            $phone,
            [
                '٠' => '0',
                '١' => '1',
                '٢' => '2',
                '٣' => '3',
                '٤' => '4',
                '٥' => '5',
                '٦' => '6',
                '٧' => '7',
                '٨' => '8',
                '٩' => '9',

                '۰' => '0',
                '۱' => '1',
                '۲' => '2',
                '۳' => '3',
                '۴' => '4',
                '۵' => '5',
                '۶' => '6',
                '۷' => '7',
                '۸' => '8',
                '۹' => '9',
            ]
        );

        /*
        |--------------------------------------------------------------------------
        | Remove Formatting
        |--------------------------------------------------------------------------
        */

        $phone = preg_replace(
            '/[\s\-\(\)\.]+/u',
            '',
            $phone
        ) ?? $phone;

        /*
        |--------------------------------------------------------------------------
        | 00 International Prefix
        |--------------------------------------------------------------------------
        */

        if (str_starts_with($phone, '00')) {
            $phone = '+'.substr(
                $phone,
                2
            );
        }

        /*
        |--------------------------------------------------------------------------
        | Already International
        |--------------------------------------------------------------------------
        */

        if (str_starts_with($phone, '+')) {
            return $this
                ->sanitizeInternationalNumber(
                    $phone
                );
        }

        /*
        |--------------------------------------------------------------------------
        | Country Code Without +
        |--------------------------------------------------------------------------
        */

        if (
            str_starts_with($phone, '966') ||
            str_starts_with($phone, '967')
        ) {
            return $this
                ->sanitizeInternationalNumber(
                    '+'.$phone
                );
        }

        /*
        |--------------------------------------------------------------------------
        | Saudi Number
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/^05\d{8}$/',
                $phone
            ) === 1
        ) {
            return '+966'.substr(
                $phone,
                1
            );
        }

        if (
            preg_match(
                '/^5\d{8}$/',
                $phone
            ) === 1
        ) {
            return '+966'.$phone;
        }

        /*
        |--------------------------------------------------------------------------
        | Yemen Number
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/^7\d{8}$/',
                $phone
            ) === 1
        ) {
            return '+967'.$phone;
        }

        if (
            preg_match(
                '/^07\d{8}$/',
                $phone
            ) === 1
        ) {
            return '+967'.substr(
                $phone,
                1
            );
        }

        return $phone;
    }

    /**
     * تنظيف الرقم الدولي.
     */
    private function sanitizeInternationalNumber(
        string $phone
    ): string {
        $digits = preg_replace(
            '/\D+/',
            '',
            $phone
        ) ?? '';

        if ($digits === '') {
            return '';
        }

        return '+'.$digits;
    }
}
